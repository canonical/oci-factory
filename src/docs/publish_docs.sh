#!/bin/bash -ex
set -o pipefail

trace_suspend() {
    case "$-" in *x*)
        set +x
        __resume_trace=1
        ;;
    esac 2>/dev/null
}

trace_resume() {
    if [ "${__resume_trace:-0}" = 1 ]; then
        unset __resume_trace
        if [[ "$RUNNER_DEBUG" == "1" ]]; then
          set -x
        fi
    fi
}

source $(dirname $0)/../shared/logs.sh

DOCS_GIT_URL='https://git.launchpad.net/~ubuntu-docker-images/ubuntu-docker-images/+git/templates'
image_name="${1}"
image_doc_filename="${2}"
image_doc_folder="${3}"
err=""

# Fixture and mock data must never be sent to a registry.
data_dry_run=$(yq -r '.dry_run // false' "${image_doc_folder}/${image_doc_filename}")
if [[ "${data_dry_run}" == "true" && "${DRY_RUN:-false}" != "true" ]]; then
    log_error "Dry-run documentation data cannot be published. Set DRY_RUN=true."
    exit 1
fi

AVAILABLE_ARCHS="$(yq -r '.releases[].architectures[]' < "${image_doc_folder}"/"${image_doc_filename}" | sort | uniq | paste -sd ',')"

# get the documentation templates
docs_dir_git=templates
git clone --depth 1 -b ROCKS-3076/improve-docs-for-hybrid-rocks "${DOCS_GIT_URL}" ${docs_dir_git}
# get the RenderDown tool used to generate the docs
git clone --depth 1 -b master https://github.com/valentinviennot/RenderDown
# install the dependencies for the RenderDown tool  
pip install -U -r ${docs_dir_git}/requirements.txt -r RenderDown/requirements.txt

# Copy the input so it remains available alongside the rendered artifacts.
folder_of_data=$(cd ${docs_dir_git} && mktemp -d -p "${PWD}")
cp "${image_doc_folder}/${image_doc_filename}" "${folder_of_data}"
# the name of the markdown file generated by RenderDown:
markdown_filename="${image_doc_filename%.*}.md"

# Render both registries before deciding whether to publish.
(cd ${docs_dir_git} && make DATADIR="${folder_of_data}" dockerhub-docs ecr-docs)
cp "${docs_dir_git}/docs/docker.io/ubuntu/${markdown_filename}" "${image_doc_folder}/doc-preview.md"
cp "${docs_dir_git}/docs/public.ecr.aws/ubuntu/${markdown_filename}" "${image_doc_folder}/ecr-about-preview.md"
cp "${docs_dir_git}/docs/public.ecr.aws/ubuntu/usage/${markdown_filename}" "${image_doc_folder}/ecr-usage-preview.md"

# Use the same JSON serializer and payloads in dry-run and live publishing.
jq -n --rawfile description "${image_doc_folder}/doc-preview.md" \
    '{full_description: $description}' > "${image_doc_folder}/dockerhub-docs.json"

# Preserve the existing ECR platform metadata while safely encoding Markdown.
ecr_archs_mapped='[]'
if [ -n "$AVAILABLE_ARCHS" ]; then
    ecr_archs="${AVAILABLE_ARCHS} $(echo "${AVAILABLE_ARCHS}" | sed 's/armhf/arm/g' | tr '[:lower:]' '[:upper:]' | sed 's/AMD64/x86-64/g')"
    ecr_archs_mapped="$(echo "$ecr_archs" | jq -R 'split(" ")')"
    if [[ "${ecr_archs}" == *"ARM64"* ]]; then
        ecr_archs_mapped="$(echo "$ecr_archs_mapped" | jq '. + ["ARM 64"]')"
    fi
fi
jq -n --rawfile usage "${image_doc_folder}/ecr-usage-preview.md" \
    --rawfile about "${image_doc_folder}/ecr-about-preview.md" \
    --argjson platforms "$ecr_archs_mapped" \
    '{architectures: ["Linux"], usageText: $usage, aboutText: $about}
     + (if ($platforms | length) > 0 then {operatingSystems: $platforms} else {} end)' \
    > "${image_doc_folder}/ecr-docs.json"

if [ "${DRY_RUN:-false}" == "true" ]; then
    log_warning "Running in dry-run mode: Markdown and JSON payloads saved; skipping registry authentication and publishing."
    exit 0
fi

### DockerHub

# Log in to Docker Hub only after all previews and payloads are ready.
dh_jw_token=$(curl -X POST  https://hub.docker.com/v2/users/login \
                -H "Content-Type: application/json" \
                -d '{"username":"'"${DOCKER_HUB_CREDS_USR_DOC}"'","password":"'"${DOCKER_HUB_CREDS_PSW_DOC}"'"}' | jq -r .token)

# We need to remove the docker.io/ before the namespace
# because we only need the namespace for the API

DH_NAMESPACE="${DOCKER_HUB_NAMESPACE#docker.io/}"

# we could also add "description" to the payload, for the image's
# short summary, but that's unlikely to ever change, so no need to 
# keep overwriting it on every build.
trace_suspend
curl -X PATCH "https://hub.docker.com/v2/repositories/${DH_NAMESPACE}/${image_name}" \
    -H "Authorization: JWT ${dh_jw_token}" \
    -H "Content-Type: application/json" \
    -d @"${image_doc_folder}/dockerhub-docs.json" --fail-with-body || err="DockerHub"
trace_resume 

### ECR

AWS_SECRET_ACCESS_KEY=${ECR_CREDS_PSW} AWS_ACCESS_KEY_ID=${ECR_CREDS_USR} \
aws --region us-east-1 ecr-public put-repository-catalog-data \
    --registry-id="${ECR_REGISTRY_ID}" --repository-name "${image_name}" --catalog-data "file://${image_doc_folder}/ecr-docs.json" || err="${err}, ECR"

# Check for error
if [ -n "${err}" ]
then
   log_error "Failed to publish docs for ${image_name} in the following registries: ${err}"
   exit 1
fi
